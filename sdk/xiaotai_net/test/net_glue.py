"""Writes the product glue the net_product_glue test compiles.

  net_glue.py <tree root> <output directory>

Runs scripts/sdk_selection.py the way a product build does for the
"configure" entry of this engine's manifest (sdk/xiaotai_net/engine.json),
once per parameter section below, and writes net_glue_<section>.c defining
net_glue_<section>(): the generated objects and the generated call of
xiaotai_net_configure. A file is rewritten only when its text changed.

The sections are the shapes the product configurations write today: a fixed
wait table, the doubling backoff with its caps and jitter (the settings of the
C3 single-key board), and the plain layout with a retry limit, serial short
passwords and unverified serial submissions; plus the network section of each
colour product as its product.json writes it.
"""
from pathlib import Path
import sys

SECTIONS = {
    "fixed_table": {
        "retry": {"steps_ms": [1000, 2000, 4000, 8000, 15000, 30000]},
        "store_unverified": True,
        "dns_fallback": "XIAOTAI_NET_DNS_FALLBACK_ALL_EMPTY",
        "driver_storage": True,
    },
    "doubling": {
        "layout": "XIAOTAI_NET_STORE_PLAIN",
        "space": "xmini",
        "provisioning": "XIAOTAI_NET_PROVISIONING_EXCLUSIVE",
        "dns_fallback": "XIAOTAI_NET_DNS_FALLBACK_NEVER",
        "retry": {
            "fast_retries": 3,
            "first_ms": 2000,
            "max_ms": 60000,
            "max_credentials_ms": 300000,
            "jitter_percent": 25,
            "grow_from_previous_base": True,
            "join_immediately_on_radio_start": True,
        },
    },
    "plain_serial": {
        "layout": "XIAOTAI_NET_STORE_PLAIN",
        "space": "net_plain",
        "retry": {"fast_retries": 10, "retries_max": 10},
        "unverified_methods": "XIAOTAI_PROVISION_SERIAL",
        "serial_short_passwords": True,
        "dns_fallback": "XIAOTAI_NET_DNS_FALLBACK_NEVER",
    },
}

PRODUCTS = {
    "szpi": "xiaotai-szpi-s3",
    "cores3": "xiaotai-cores3-lite",
    "waveshare": "xiaotai-waveshare-p4-rev3",
    "wt99": "xiaotai-wt99p461-s1-1v1",
}


def source(selection, unit, name, values):
    glue, headers, calls = selection._glue([], [unit], {"parameters": {unit.name: values}})
    if not calls:
        raise SystemExit(f"net_glue.py: section {name} produced no configure call")
    text = ["// Generated by sdk/xiaotai_net/test/net_glue.py. Do not edit.\n",
            "#include <stddef.h>\n#include <stdint.h>\n"]
    text += [f'#include "{header}"\n' for header in headers]
    text.append("\n")
    text += glue.objects
    text.append(f"\nxiaotai_err_t net_glue_{name}(void);\n"
                f"xiaotai_err_t net_glue_{name}(void)\n{{\n    xiaotai_err_t err = XIAOTAI_OK;\n")
    text += [call + "    if (err != XIAOTAI_OK) return err;\n" for call in calls]
    text.append("    return err;\n}\n")
    return "".join(text)


def main(argv):
    if len(argv) != 3:
        raise SystemExit(__doc__)
    root, out = Path(argv[1]).resolve(), Path(argv[2])
    sys.path.insert(0, str(root / "scripts"))
    import sdk_selection  # noqa: E402 (path set above)

    unit = sdk_selection.catalog(root)["module"]["net"]
    sections = dict(SECTIONS)
    for name, product in PRODUCTS.items():
        path = root / "products" / product / "product.json"
        sections[name] = sdk_selection.load_product(path)["parameters"]["net"]
    out.mkdir(parents=True, exist_ok=True)
    for name, values in sections.items():
        text = source(sdk_selection, unit, name, values)
        path = out / f"net_glue_{name}.c"
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            with open(path, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
