#!/usr/bin/env python3
"""Rebuild the wide door's LVGL 9 font subsets from the retained OFL sources.

Generation uses Pillow with FreeType and fontTools. `--check` is dependency
free and verifies reviewed generated data against current strings and hashes.
Do not install or download anything as part of a firmware build.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "apps/xiaotai_app_door"
SOURCE = ROOT / "components/xiaotai_lvgl/fonts/source"
SOURCES = {
    "noto": (SOURCE / "NotoSansSC[wght].ttf",
             "a3041811a78c361b1de50f953c805e0244951c21c5bd412f7232ef0d899af0da",
             "Copyright 2014-2021 Adobe, with Reserved Font Name 'Source'.", "OFL-NotoSansSC.txt"),
    "inter": (APP / "assets/source/inter/Inter.ttf",
              "29160a80ff49ddcab2c97711247e08b1fab27a484a329ce8b813d820dc559031",
              "Copyright 2020 The Inter Project Authors (https://github.com/rsms/inter).", "OFL-Inter.txt"),
}
# Match the weights and native line/baseline metrics of the prior door UI.
FONTS = {
    "door_font_small": ("noto", 18, 500, 27, 6),
    "door_font_button": ("noto", 24, 500, 35, 7),
    "door_font_body": ("noto", 24, 400, 35, 7),
    "door_font_dialog": ("noto", 26, 500, 38, 8),
    "door_font_title": ("noto", 32, 500, 47, 10),
    "door_font_clock": ("inter", 128, 300, 144, 26),
}
C_TOKEN = re.compile(r'//[^\n]*|/\*.*?\*/|"(?:[^"\\]|\\.)*"|\'(?:[^\'\\]|\\.)*\'', re.S)
CLOCK = {ord(ch) for ch in " -:0123456789"}


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def required_chars(products: list[Path]) -> set[int]:
    chars = set(range(32, 127))
    sources = sorted((APP / "src").iterdir())
    for source in (path for path in sources if path.suffix in {".c", ".h"}):
        for token in C_TOKEN.findall(source.read_text(encoding="utf-8")):
            if token.startswith('"'):
                chars.update(ord(ch) for ch in token[1:-1] if ch.isprintable())
    for path in products:
        product = json.loads(path.read_text(encoding="utf-8"))
        if "door" not in product.get("applications", []):
            continue
        configs = [product.get("parameters", {})]
        configs.extend(v.get("parameters", {}) for v in product.get("variants", {}).values())
        for parameters in configs:
            door = parameters.get("door", {})
            for key in ("title", "door_name"):
                value = door.get(key)
                if value is not None and not isinstance(value, str):
                    raise ValueError(f"{path}: door.{key} must be text")
                chars.update(ord(ch) for ch in value or "" if ch.isprintable())
    return chars


def lines(values: list[str], columns: int) -> str:
    return "\n".join("    " + ", ".join(values[i:i + columns]) + "," for i in range(0, len(values), columns))


def coverage_header(chars: set[int]) -> bytes:
    tables = [("door_text_codepoints", chars), ("door_clock_codepoints", CLOCK)]
    return ("/* Generated by scripts/generate_door_fonts.py for the host fixture. */\n"
            "#pragma once\n#include <stdint.h>\n\n"
            + "\n".join(f"static const uint32_t {name}[] = {{\n"
                        f'{lines([f"0x{ch:04x}" for ch in sorted(codepoints)], 10)}\n}};\n'
                        for name, codepoints in tables)).encode("ascii")


def build_font(name: str, chars: list[int], args: tuple, supported: dict[str, set[int]]) -> str:
    from PIL import ImageFont

    family, size, weight, height, baseline = args
    source, digest, copyright_, license_ = SOURCES[family]
    missing = set(chars) - supported[family]
    if missing:
        raise ValueError(f"{name}: missing authored characters: {','.join(f'U+{c:04X}' for c in sorted(missing))}")
    font = ImageFont.truetype(str(source), size, layout_engine=ImageFont.Layout.BASIC)
    axes = font.get_variation_axes()
    font.set_variation_by_axes([weight if axis["name"] == b"Weight" else axis["default"] for axis in axes])
    bitmap = bytearray()
    descriptors = ["    {0},"]
    for codepoint in chars:
        char = chr(codepoint)
        mask, (x, y) = font.getmask2(char, mode="L", anchor="ls")
        width, rows = mask.size
        if not rows:
            width = x = y = 0
        values = [(255 // 2 + v * 15) // 255 for v in bytes(mask)]
        values += [0] * (len(values) & 1)
        adv = round(16 * font.getlength(char))
        descriptors.append(f"    {{.bitmap_index={len(bitmap)},.adv_w={adv},.box_w={width},.box_h={rows},"
                           f".ofs_x={x},.ofs_y={-y - rows}}},")
        bitmap.extend(values[i] << 4 | values[i + 1] for i in range(0, len(values), 2))
    start = chars[0]
    if chars[-1] - start >= 65535:
        raise ValueError(f"{name}: subset needs additional LVGL ranges for non-BMP characters")
    return f'''/* SPDX-License-Identifier: OFL-1.1
 * {copyright_}
 * Modified font, {size} px, weight {weight}. Source sha256: {digest}
 * License: ../{license_}. Generated by scripts/generate_door_fonts.py.
 */
#include "lvgl.h"

static const LV_ATTRIBUTE_LARGE_CONST uint8_t glyph_bitmap[] = {{
{lines([f"0x{v:02x}" for v in bitmap], 16)}
}};
static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{chr(10).join(descriptors)}
}};
static const uint16_t unicode_list[] = {{
{lines([str(c - start) for c in chars], 12)}
}};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start={start}, .range_length={chars[-1] - start + 1}, .glyph_id_start=1,
      .unicode_list=unicode_list, .list_length={len(chars)}, .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}},
}};
static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap=glyph_bitmap, .glyph_dsc=glyph_dsc, .cmaps=cmaps,
    .cmap_num=1, .bpp=4, .bitmap_format=LV_FONT_FMT_TXT_PLAIN,
}};
const lv_font_t {name} = {{
    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,
    .line_height={height}, .base_line={baseline}, .subpx=LV_FONT_SUBPX_NONE, .dsc=&font_dsc,
}};
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--product", type=Path, action="append", help="Extra product manifest including custom door text")
    parser.add_argument("--out-dir", type=Path, default=APP / "assets/fonts")
    args = parser.parse_args()
    products = sorted(ROOT.glob("products/*/product.json")) + (args.product or [])
    chars = required_chars(products)
    expected = {name: sorted(CLOCK if group == "inter" else chars) for name, (group, *_) in FONTS.items()}
    output = args.out_dir
    manifest_path = output / "manifest.json"
    coverage_path = output / "coverage.h"
    coverage = coverage_header(chars)
    if args.check:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        if manifest["sources"] != {family: digest for family, (_, digest, _, _) in SOURCES.items()}:
            raise SystemExit("Font source manifest differs from the pinned sources")
        if set(manifest["fonts"]) != expected.keys() or coverage_path.read_bytes() != coverage:
            raise SystemExit("Regenerate the font coverage tables")
        for name, codepoints in expected.items():
            actual = manifest["fonts"][name]
            data = (output / f"{name}.c").read_bytes()
            if actual != {"codepoints": codepoints, "sha256": sha(data), "bytes": len(data)}:
                raise SystemExit(f"{name}: regenerate the font subset")
        print(f"PASS: {len(chars)} authored glyphs, {len(CLOCK)} clock glyphs, six checked subsets")
        return

    from PIL import __version__, features
    import fontTools
    from fontTools.ttLib import TTFont

    supported: dict[str, set[int]] = {}
    for family, (source, digest, _, _) in SOURCES.items():
        if sha(source.read_bytes()) != digest:
            raise ValueError(f"{source}: does not match the retained font source")
        with TTFont(source, lazy=True) as outline:
            supported[family] = set(outline.getBestCmap())
    output.mkdir(parents=True, exist_ok=True)
    manifest = {"generator": "scripts/generate_door_fonts.py", "pillow": __version__,
                "freetype": features.version_module("freetype2"), "fontTools": fontTools.__version__,
                "sources": {family: digest for family, (_, digest, _, _) in SOURCES.items()}, "fonts": {}}
    for name, codepoints in expected.items():
        data = build_font(name, codepoints, FONTS[name], supported).encode("ascii")
        (output / f"{name}.c").write_bytes(data)
        manifest["fonts"][name] = {"codepoints": codepoints, "sha256": sha(data), "bytes": len(data)}
    coverage_path.write_bytes(coverage)
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
