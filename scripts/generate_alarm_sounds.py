"""Synthesize the two sounds of the alarm application (8 kHz A-law, mono).

    python3 scripts/generate_alarm_sounds.py            # write the table
    python3 scripts/generate_alarm_sounds.py --wav DIR  # also write WAV files to listen to

bell   a wind-up alarm clock: a hammer between two bells
timer  a kitchen timer: four short beeps
Nothing is sampled from a recording; every number below is the sound.
"""

import argparse
import math
from pathlib import Path
import struct
import wave

RATE = 8000
OUT = Path(__file__).resolve().parents[1] / "apps/xiaotai_app_alarm/src/alarm_sounds_data.inc"


def bell():
    total, ringing = int(1.85 * RATE), 1.5
    out = [0.0] * total
    # Partials of a small struck cup: frequency, level, decay time in seconds.
    cups = [[(1180, 1.0, 0.16), (1795, 0.7, 0.11), (2390, 0.55, 0.08), (3240, 0.35, 0.05)],
            [(1335, 1.0, 0.16), (2030, 0.7, 0.11), (2700, 0.5, 0.08), (3560, 0.3, 0.05)]]
    strikes, t, side = [], 0.0, 0
    while t < ringing:
        strikes.append((t, side, 1.0 if len(strikes) % 2 == 0 else 0.9))
        t, side = t + 1 / 23, 1 - side
    for at, cup, force in strikes:
        first = int(at * RATE)
        for n in range(first, total):
            s = (n - first) / RATE
            if s > 0.6:
                break
            attack = min(1.0, s / 0.0015)
            out[n] += force * attack * sum(level * math.exp(-s / decay) * math.sin(2 * math.pi * f * s)
                                           for f, level, decay in cups[cup])
    fade = int(0.03 * RATE)
    for n in range(fade):
        out[total - 1 - n] *= n / fade
    return out


def timer():
    out = []
    for _ in range(4):
        on, off = int(0.075 * RATE), int(0.055 * RATE)
        for n in range(on):
            s = n / RATE
            edge = min(1.0, n / 24, (on - n) / 24)
            out.append(edge * (math.sin(2 * math.pi * 2048 * s) + 0.35 * math.sin(2 * math.pi * 1024 * s)))
        out += [0.0] * off
    return out


def level(samples, drive):
    peak = max(abs(v) for v in samples)
    return [math.tanh(drive * v / peak) / math.tanh(drive) * 0.92 for v in samples]


def alaw(value):
    pcm = int(round(value * 32767)) >> 3
    sign = 0xD5
    if pcm < 0:
        sign, pcm = 0x55, -pcm - 1
    for segment, end in enumerate((0x1F, 0x3F, 0x7F, 0xFF, 0x1FF, 0x3FF, 0x7FF, 0xFFF)):
        if pcm <= end:
            break
    else:
        return 0x7F ^ sign
    low = (pcm >> 1) & 0x0F if segment < 2 else (pcm >> segment) & 0x0F
    return (segment << 4 | low) ^ sign


def table(name, samples):
    data = [alaw(v) for v in samples]
    rows = [", ".join(str(b) for b in data[i:i + 24]) + "," for i in range(0, len(data), 24)]
    return f"static const uint8_t {name}[] = {{\n" + "\n".join(rows) + "\n};\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--wav", type=Path)
    args = parser.parse_args()
    sounds = {"alarm_bell": level(bell(), 1.6), "alarm_timer": level(timer(), 1.2)}
    text = "// SPDX-License-Identifier: MIT\n// Generated by scripts/generate_alarm_sounds.py: 8 kHz A-law, mono.\n"
    OUT.write_text(text + "".join(table(n, s) for n, s in sounds.items()), encoding="utf-8", newline="\n")
    for name, samples in sounds.items():
        print(name, len(samples), "bytes", f"{len(samples) / RATE:.2f} s")
        if args.wav:
            args.wav.mkdir(parents=True, exist_ok=True)
            with wave.open(str(args.wav / f"{name}.wav"), "wb") as f:
                f.setnchannels(1)
                f.setsampwidth(2)
                f.setframerate(RATE)
                loop = samples + [0.0] * int((0.35 if name == "alarm_bell" else 0.5) * RATE)
                f.writeframes(b"".join(struct.pack("<h", int(v * 32767)) for v in loop * 3))


if __name__ == "__main__":
    main()
