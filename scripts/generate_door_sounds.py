"""Synthesize the sounds of the door application (8 kHz A-law, mono).

    python3 scripts/generate_door_sounds.py            # write the table
    python3 scripts/generate_door_sounds.py --wav DIR  # also write WAV files to listen to

opened  the lock gives way: three notes going up, the last one rings on
key     a key of the keypad: one short soft note
Nothing is sampled from a recording; every number below is the sound.
"""

import argparse
import math
from pathlib import Path
import struct
import wave

from generate_alarm_sounds import RATE, level, table

OUT = Path(__file__).resolve().parents[1] / "apps/xiaotai_app_door/src/door_sounds_data.inc"


def opened():
    notes = [(0.00, 1046.5, 0.18), (0.11, 1318.5, 0.18), (0.22, 1568.0, 0.42)]     # C6 E6 G6: start, frequency, decay
    out = [0.0] * int(0.95 * RATE)
    for at, f, decay in notes:
        first = int(at * RATE)
        for n in range(first, len(out)):
            s = (n - first) / RATE
            edge = min(1.0, s / 0.004)
            out[n] += edge * math.exp(-s / decay) * (math.sin(2 * math.pi * f * s) + 0.25 * math.sin(4 * math.pi * f * s))
    fade = int(0.06 * RATE)
    for n in range(fade):
        out[-1 - n] *= n / fade
    return out


def key():
    count = int(0.06 * RATE)
    return [min(1.0, n / 32, (count - n) / 160) * math.sin(2 * math.pi * 880 * n / RATE) for n in range(count)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--wav", type=Path)
    args = parser.parse_args()
    sounds = {"door_opened": level(opened(), 1.1), "door_key": [0.4 * v for v in level(key(), 1.0)]}
    text = "// SPDX-License-Identifier: MIT\n// Generated by scripts/generate_door_sounds.py: 8 kHz A-law, mono.\n"
    OUT.write_text(text + "".join(table(n, s) for n, s in sounds.items()), encoding="utf-8", newline="\n")
    for name, samples in sounds.items():
        print(name, len(samples), "bytes", f"{len(samples) / RATE:.2f} s")
        if args.wav:
            args.wav.mkdir(parents=True, exist_ok=True)
            with wave.open(str(args.wav / f"{name}.wav"), "wb") as f:
                f.setnchannels(1)
                f.setsampwidth(2)
                f.setframerate(RATE)
                f.writeframes(b"".join(struct.pack("<h", int(v * 32767)) for v in samples))


if __name__ == "__main__":
    main()
